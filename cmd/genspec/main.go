// genspec écrit internal/integ/spec_gen.go : pour chaque type d'intégration,
// les rôles de secrets et les options lus par son code, et la description de
// sa page de doc. Sert au formulaire d'ajout de l'interface.
// Usage (racine du dépôt) : go run ./cmd/genspec
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

func main() {
	fset := token.NewFileSet()
	pkgDir := "internal/integ"
	files, _ := filepath.Glob(filepath.Join(pkgDir, "*.go"))
	funcFile := map[string]string{}
	roles, opts := map[string][]string{}, map[string][]string{}
	var registry map[string]string
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") || strings.HasSuffix(f, "spec_gen.go") {
			continue
		}
		af, err := parser.ParseFile(fset, f, nil, 0)
		if err != nil {
			log.Fatal(err)
		}
		ast.Inspect(af, func(n ast.Node) bool {
			switch x := n.(type) {
			case *ast.FuncDecl:
				if x.Recv == nil {
					funcFile[x.Name.Name] = f
				}
			case *ast.CallExpr:
				if id, ok := x.Fun.(*ast.Ident); ok && id.Name == "secret" && len(x.Args) == 1 {
					if s, ok := lit(x.Args[0]); ok {
						roles[f] = append(roles[f], s)
					}
				}
			case *ast.IndexExpr:
				if sel, ok := x.X.(*ast.SelectorExpr); ok && sel.Sel.Name == "Options" {
					if s, ok := lit(x.Index); ok {
						opts[f] = append(opts[f], s)
					}
				}
			case *ast.ValueSpec:
				if len(x.Names) == 1 && x.Names[0].Name == "registry" && len(x.Values) == 1 {
					registry = readRegistry(x.Values[0])
				}
			}
			return true
		})
	}
	if len(registry) == 0 {
		log.Fatal("registry introuvable")
	}
	types := make([]string, 0, len(registry))
	for t := range registry {
		types = append(types, t)
	}
	slices.Sort(types)
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/genspec; DO NOT EDIT.\n\npackage integ\n\nvar specs = map[string]Spec{\n")
	for _, t := range types {
		f := funcFile[registry[t]]
		fmt.Fprintf(&b, "\t%q: {Secrets: %s, Options: %s, Desc: %q},\n", t, list(roles[f]), list(opts[f]), desc(t))
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(pkgDir, "spec_gen.go"), out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func lit(e ast.Expr) (string, bool) {
	bl, ok := e.(*ast.BasicLit)
	if !ok || bl.Kind != token.STRING {
		return "", false
	}
	s, err := strconv.Unquote(bl.Value)
	return s, err == nil && s != ""
}

// readRegistry : type → nom de la fabrique (premier élément de la valeur).
func readRegistry(e ast.Expr) map[string]string {
	out := map[string]string{}
	cl, ok := e.(*ast.CompositeLit)
	if !ok {
		return out
	}
	for _, el := range cl.Elts {
		kv, ok := el.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		k, ok := lit(kv.Key)
		v, ok2 := kv.Value.(*ast.CompositeLit)
		if !ok || !ok2 || len(v.Elts) == 0 {
			continue
		}
		if id, ok := v.Elts[0].(*ast.Ident); ok {
			out[k] = id.Name
		}
	}
	return out
}

func list(s []string) string {
	s = slices.Clone(s)
	slices.Sort(s)
	s = slices.Compact(s)
	if len(s) == 0 {
		return "nil"
	}
	return fmt.Sprintf("%#v", s)
}

// desc : première ligne de texte de docs/integrations/<type>.md.
func desc(t string) string {
	f, err := os.Open(filepath.Join("docs", "fr", "integrations", t+".md"))
	if err != nil {
		return ""
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		l := strings.TrimSpace(sc.Text())
		if l != "" && !strings.HasPrefix(l, "#") && !strings.HasPrefix(l, "```") && !strings.HasPrefix(l, "|") && !strings.HasPrefix(l, ">") {
			return strings.Trim(l, "*_ ")
		}
	}
	return ""
}
